/** \file
 * Host-side key/value filler for the DMA Iuventus GROUP BY user core.
 *
 * Writes 16 B {uint64_t key, uint64_t value} records to one or more NVMe drives entirely over
 * ordinary SPDK NVMe I/O queue pairs -- host DRAM buffers, no FPGA involved. This intentionally
 * does NOT use the iuventus environment library (lib/iuventus): that library maps the card's BARs
 * and creates queue pairs INSIDE them for the peer-to-peer path, which is ~7x slower than a plain
 * host write and gives no control over the key distribution. kv_fill only borrows the -t <trid>
 * convention from it for a familiar command line; discovery itself is plain spdk_nvme_probe().
 *
 * Record i of a drive seeded S is generated by splitmix64(), addressed by index rather than by
 * mutating a running state so any record can be produced independently of its neighbours:
 *
 * \code
 *   uint64_t splitmix64(uint64_t seed, uint64_t index) {
 *       uint64_t x = seed + index + 0x9E3779B97F4A7C15ULL;
 *       uint64_t z = x;
 *       z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ULL;
 *       z = (z ^ (z >> 27)) * 0x94D049BB133111EBULL;
 *       return z ^ (z >> 31);
 *   }
 *
 *   key   (uniform mode) = splitmix64(seed, 2*i)     % KV_FILL_KEY_MOD
 *   key   (zipf mode)    = zipf_rank(splitmix64(seed, 2*i) mapped to a double in [0,1))
 *   value                = splitmix64(seed, 2*i + 1)
 * \endcode
 *
 * This is bit-for-bit the function apps/iuventus/sw/iuventus_groupby.py implements in Python as
 * splitmix64()/splitmix64_records() -- both sides must stay in lockstep, which --selftest is for:
 * it prints the first 8 records with no drive attached, to diff by hand against the Python side.
 *
 * Each drive is filled by its own thread and its own I/O qpair, so the wall time for N drives is
 * one drive's fill, not N of them back to back. While generating, every record is also folded
 * into a per-key {sum, count} table that is written out as a JSON sidecar once the drive is done
 * -- see write_sidecar() for the exact schema.
 */

#include "spdk/stdinc.h"

#include "spdk/env.h"
#include "spdk/nvme.h"
