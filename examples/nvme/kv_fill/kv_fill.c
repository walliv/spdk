/* CPU set the process had before spdk_env_init() narrowed it to the SPDK core mask. Worker threads
 * are plain pthreads, so without this they all inherit that one core and the fills serialise. */
static cpu_set_t g_startup_cpus;
static int g_startup_cpu_count;

static void
pin_worker_to_own_cpu(unsigned index)
{
	cpu_set_t one;
	int cpu, seen = 0;

	if (g_startup_cpu_count <= 0) {
		return;
	}
	for (cpu = 0; cpu < CPU_SETSIZE; cpu++) {
		if (!CPU_ISSET(cpu, &g_startup_cpus)) {
			continue;
		}
		if (seen == (int)(index % (unsigned)g_startup_cpu_count)) {
			CPU_ZERO(&one);
			CPU_SET(cpu, &one);
			pthread_setaffinity_np(pthread_self(), sizeof(one), &one);
			return;
		}
		seen++;
	}
}

/*
 * Record layout: 16 B little-endian {key, value}, 32 records per 512 B sector. Both constants
 * are load-bearing for apps/iuventus/comp's GROUP BY core and apps/iuventus/sw/iuventus_groupby.py
 * -- do not change either without changing all three.
 */
#define KV_REC_BYTES			16u
#define KV_SECT_BYTES			512u
#define KV_RECS_PER_SECTOR		(KV_SECT_BYTES / KV_REC_BYTES)

/* Key modulus, matching SPLITMIX_KEY_MOD / the shipping GROUP BY table size in
 * apps/iuventus/sw/iuventus_groupby.py. Every generated key -- uniform or zipf -- lands in
 * [0, KV_FILL_KEY_MOD), so OOR_CNT on the FPGA side is expected to stay at zero for this data. */
#define KV_FILL_KEY_MOD			16384u

#define KV_FILL_MAX_DRIVES		8u
#define KV_FILL_DEFAULT_SECTORS		(1ULL << 31)	/* 1 TiB per drive at 512 B sectors */
#define KV_FILL_DEFAULT_IO_SIZE_KIB	128u
#define KV_FILL_DEFAULT_QUEUE_DEPTH	32u

/* YCSB's canonical "core workload" skew -- a well-known, citable value rather than an arbitrary
 * one, so a reader who knows YCSB already knows roughly how hot the hottest key is. */
#define KV_FILL_ZIPF_THETA_DEFAULT	0.99

#define SPLITMIX_GAMMA			0x9E3779B97F4A7C15ULL
#define SPLITMIX_MIX_1			0xBF58476D1CE4E5B9ULL
#define SPLITMIX_MIX_2			0x94D049BB133111EBULL

enum kv_dist {
	KV_DIST_UNIFORM = 0,
	KV_DIST_ZIPF,
};

/*
 * Parameters of a Zipfian distribution over KV_FILL_KEY_MOD ranks, plus the constants the
 * generator below needs so they are computed once instead of on every record.
 */
struct zipf_table {
	uint32_t	n;
	double		theta;
	double		alpha;
	double		zetan;
	double		eta;
};

/*
 * zeta(n, theta) = sum_{i=1}^{n} 1/i^theta, the generalised harmonic number the Zipf PMF is
 * normalised by. O(n) with n == KV_FILL_KEY_MOD is a sub-millisecond, run-once cost.
 */
static double
zeta(uint32_t n, double theta)
{
	double sum = 0.0;
	uint32_t i;

	for (i = 1; i <= n; i++) {
		sum += 1.0 / pow((double)i, theta);
	}
	return sum;
}

/*
 * The closed-form Zipfian generator from Gray et al., "Quickly Generating Billion-Record
 * Synthetic Databases" (SIGMOD 1994) -- the same algorithm YCSB ships as ZipfianGenerator. Ranks
 * are 0-based, rank 0 being the single hottest key; no scrambling is applied, so which key is hot
 * is a plain, reproducible function of theta alone.
 */
static void
zipf_table_init(struct zipf_table *zt, uint32_t n, double theta)
{
	double zeta2 = zeta(2, theta);

	zt->n = n;
	zt->theta = theta;
	zt->alpha = 1.0 / (1.0 - theta);
	zt->zetan = zeta(n, theta);
	zt->eta = (1.0 - pow(2.0 / (double)n, 1.0 - theta)) / (1.0 - zeta2 / zt->zetan);
}

/* `u` must be uniform over [0, 1); see splitmix64_to_unit(). Returned rank is always < zt->n. */
static uint64_t
zipf_rank(const struct zipf_table *zt, double u)
{
	double uz = u * zt->zetan;
	uint64_t rank;

	if (uz < 1.0) {
		rank = 0;
	} else if (uz < 1.0 + pow(0.5, zt->theta)) {
		rank = 1;
	} else {
		rank = (uint64_t)((double)zt->n * pow(zt->eta * u - zt->eta + 1.0, zt->alpha));
	}

	return spdk_min(rank, (uint64_t)zt->n - 1);
}

/*
 * One splitmix64 draw, addressed by index instead of by mutating a running state. This is the
 * SAME function apps/iuventus/sw/iuventus_groupby.py implements as splitmix64() -- see that
 * docstring, which is the normative definition this was transcribed from bit for bit. uint64_t
 * arithmetic already wraps modulo 2^64, matching the Python side's explicit "& MASK64".
 */
static inline uint64_t
splitmix64(uint64_t seed, uint64_t index)
{
	uint64_t x = seed + index + SPLITMIX_GAMMA;
	uint64_t z = x;

	z = (z ^ (z >> 30)) * SPLITMIX_MIX_1;
	z = (z ^ (z >> 27)) * SPLITMIX_MIX_2;
	return z ^ (z >> 31);
}

/* Top 53 bits of a splitmix64 draw -> the full mantissa a double holds, giving u uniform over
 * [0, 1). Same technique commonly used to convert a 64-bit PRNG draw to a double. */
static inline double
splitmix64_to_unit(uint64_t draw)
{
	return (double)(draw >> 11) * (1.0 / 9007199254740992.0);	/* 1.0 / 2^53 */
}

static inline void
store_le64(uint8_t *p, uint64_t v)
{
	int i;

	for (i = 0; i < 8; i++) {
		p[i] = (uint8_t)(v >> (8 * i));
	}
}

/*
 * One drive's fill: owned exclusively by its own thread from pthread_create() to pthread_join(),
 * except for ctrlr/ns which probe_cb()/attach_cb() fill in on the main thread beforehand.
 */
struct drive_ctx {
	/* Set by main() before the probe; read-only from here on. */
	uint32_t				index;
	struct spdk_nvme_transport_id		trid;
	uint64_t				seed;
	enum kv_dist				dist;
	double					zipf_theta;
	const struct zipf_table		*zt;
	uint64_t				start_lba;
	uint64_t				total_sectors;
	uint32_t				io_size_kib;
	uint32_t				queue_depth;
	const char				*sidecar_dir;
	uint64_t				*group_sum;	/* [KV_FILL_KEY_MOD] */
	uint64_t				*group_count;	/* [KV_FILL_KEY_MOD] */

	/* Filled in by attach_cb() on the main thread, before any worker thread is started. */
	struct spdk_nvme_ctrlr			*ctrlr;
	struct spdk_nvme_ns			*ns;

	/* Owned solely by fill_worker() -- main() only reads these after pthread_join(). */
	struct spdk_nvme_qpair			*qpair;
	uint64_t				sectors_done;
	uint64_t				oor_count;
	bool					had_error;
	uint64_t				first_error_lba;
	double					elapsed_seconds;
	double					throughput_gbps;
	char					sidecar_path[PATH_MAX];
};

struct kv_fill_ctx {
	struct drive_ctx	drives[KV_FILL_MAX_DRIVES];
	uint32_t		num_drives;
};

/* Raw command-line options, before per-drive seeds/sector counts are resolved. */
struct kv_fill_opts {
	struct spdk_nvme_transport_id	trid[KV_FILL_MAX_DRIVES];
	uint32_t			num_trids;

	uint64_t			seed[KV_FILL_MAX_DRIVES];
	uint32_t			num_seeds;

	enum kv_dist			dist;
	double				zipf_theta;
	bool				zipf_theta_set;

	uint64_t			sectors;
	bool				sectors_set;
	uint64_t			gib;
	bool				gib_set;

	uint64_t			start_lba;
	uint32_t			io_size_kib;
	uint32_t			queue_depth;
	const char			*sidecar_dir;
	bool				selftest;
};

static bool
is_pow2_u64(uint64_t v)
{
	return v != 0 && (v & (v - 1)) == 0;
}

static void
opts_init(struct kv_fill_opts *opts)
{
	memset(opts, 0, sizeof(*opts));
	opts->dist = KV_DIST_UNIFORM;
	opts->zipf_theta = KV_FILL_ZIPF_THETA_DEFAULT;
	opts->io_size_kib = KV_FILL_DEFAULT_IO_SIZE_KIB;
	opts->queue_depth = KV_FILL_DEFAULT_QUEUE_DEPTH;
	opts->sidecar_dir = ".";
}

