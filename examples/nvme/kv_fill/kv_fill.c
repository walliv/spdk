enum kv_fill_long_opt {
	KV_OPT_SEED = 256,
	KV_OPT_DIST,
	KV_OPT_ZIPF_THETA,
	KV_OPT_SECTORS,
	KV_OPT_GIB,
	KV_OPT_START_LBA,
	KV_OPT_IO_SIZE_KIB,
	KV_OPT_QUEUE_DEPTH,
	KV_OPT_SIDECAR_DIR,
	KV_OPT_SELFTEST,
};

#define KV_FILL_GETOPT_STRING "ht:"

static const struct option g_kv_fill_cmdline_opts[] = {
	{"seed",		required_argument,	NULL, KV_OPT_SEED},
	{"dist",		required_argument,	NULL, KV_OPT_DIST},
	{"zipf-theta",		required_argument,	NULL, KV_OPT_ZIPF_THETA},
	{"sectors",		required_argument,	NULL, KV_OPT_SECTORS},
	{"gib",			required_argument,	NULL, KV_OPT_GIB},
	{"start-lba",		required_argument,	NULL, KV_OPT_START_LBA},
	{"io-size-kib",		required_argument,	NULL, KV_OPT_IO_SIZE_KIB},
	{"queue-depth",		required_argument,	NULL, KV_OPT_QUEUE_DEPTH},
	{"sidecar-dir",		required_argument,	NULL, KV_OPT_SIDECAR_DIR},
	{"selftest",		no_argument,		NULL, KV_OPT_SELFTEST},
	{"help",		no_argument,		NULL, 'h'},
	{0, 0, 0, 0}
};

static int
parse_args(int argc, char **argv, struct kv_fill_opts *opts)
{
	int op, opt_index;
	long long val;

	while ((op = getopt_long(argc, argv, KV_FILL_GETOPT_STRING, g_kv_fill_cmdline_opts,
				 &opt_index)) != -1) {
		switch (op) {
		case 't':
			if (opts->num_trids >= KV_FILL_MAX_DRIVES) {
				fprintf(stderr, "at most %u drives are supported\n",
					KV_FILL_MAX_DRIVES);
				return -1;
			}
			opts->trid[opts->num_trids].trtype = SPDK_NVME_TRANSPORT_PCIE;
			if (spdk_nvme_transport_id_parse(&opts->trid[opts->num_trids],
							 optarg) != 0) {
				fprintf(stderr, "invalid transport ID '%s'\n", optarg);
				return -1;
			}
			opts->num_trids++;
			break;
		case KV_OPT_SEED:
			if (opts->num_seeds >= KV_FILL_MAX_DRIVES) {
				fprintf(stderr, "at most %u --seed values are supported\n",
					KV_FILL_MAX_DRIVES);
				return -1;
			}
			val = spdk_strtoll(optarg, 0);
			if (val < 0) {
				fprintf(stderr, "invalid --seed '%s'\n", optarg);
				return -1;
			}
			opts->seed[opts->num_seeds++] = (uint64_t)val;
			break;
		case KV_OPT_DIST:
			if (strcmp(optarg, "uniform") == 0) {
				opts->dist = KV_DIST_UNIFORM;
			} else if (strcmp(optarg, "zipf") == 0) {
				opts->dist = KV_DIST_ZIPF;
			} else {
				fprintf(stderr, "--dist must be 'uniform' or 'zipf', not '%s'\n",
					optarg);
				return -1;
			}
			break;
		case KV_OPT_ZIPF_THETA:
			opts->zipf_theta = atof(optarg);
			opts->zipf_theta_set = true;
			break;
		case KV_OPT_SECTORS:
			val = spdk_strtoll(optarg, 0);
			if (val <= 0) {
				fprintf(stderr, "invalid --sectors '%s'\n", optarg);
				return -1;
			}
			opts->sectors = (uint64_t)val;
			opts->sectors_set = true;
			break;
		case KV_OPT_GIB:
			val = spdk_strtoll(optarg, 0);
			if (val <= 0) {
				fprintf(stderr, "invalid --gib '%s'\n", optarg);
				return -1;
			}
			opts->gib = (uint64_t)val;
			opts->gib_set = true;
			break;
		case KV_OPT_START_LBA:
			val = spdk_strtoll(optarg, 0);
			if (val < 0) {
				fprintf(stderr, "invalid --start-lba '%s'\n", optarg);
				return -1;
			}
			opts->start_lba = (uint64_t)val;
			break;
		case KV_OPT_IO_SIZE_KIB:
			val = spdk_strtoll(optarg, 0);
			if (val <= 0) {
				fprintf(stderr, "invalid --io-size-kib '%s'\n", optarg);
				return -1;
			}
			opts->io_size_kib = (uint32_t)val;
			break;
		case KV_OPT_QUEUE_DEPTH:
			val = spdk_strtoll(optarg, 0);
			if (val <= 0) {
				fprintf(stderr, "invalid --queue-depth '%s'\n", optarg);
				return -1;
			}
			opts->queue_depth = (uint32_t)val;
			break;
		case KV_OPT_SIDECAR_DIR:
			opts->sidecar_dir = optarg;
			break;
		case KV_OPT_SELFTEST:
			opts->selftest = true;
			break;
		case 'h':
			usage(argv[0]);
			exit(EXIT_SUCCESS);
		default:
			usage(argv[0]);
			return -1;
		}
	}

	return 0;
}

/* Resolves --sectors/--gib into *out_sectors and checks every cross-option constraint that
 * cannot be caught while a single option is still being parsed. Not called for --selftest. */
static int
validate_opts(struct kv_fill_opts *opts, uint64_t *out_sectors)
{
	uint32_t i, j;

	if (opts->num_trids == 0) {
		fprintf(stderr, "at least one -t <trid> is required (or pass --selftest)\n");
		return -1;
	}

	for (i = 0; i < opts->num_trids; i++) {
		for (j = i + 1; j < opts->num_trids; j++) {
			if (strcmp(opts->trid[i].traddr, opts->trid[j].traddr) == 0) {
				fprintf(stderr, "drive '%s' given more than once\n",
					opts->trid[i].traddr);
				return -1;
			}
		}
	}

	if (opts->sectors_set && opts->gib_set) {
		fprintf(stderr, "--sectors and --gib are mutually exclusive\n");
		return -1;
	}

	if (opts->gib_set) {
		if (!is_pow2_u64(opts->gib) || opts->gib > (UINT64_MAX >> 21)) {
			fprintf(stderr, "--gib must be a power of two, not %" PRIu64 "\n",
				opts->gib);
			return -1;
		}
		*out_sectors = opts->gib << 21;	/* GiB -> 512 B sectors: * 2^30 / 2^9 */
	} else if (opts->sectors_set) {
		*out_sectors = opts->sectors;
	} else {
		*out_sectors = KV_FILL_DEFAULT_SECTORS;
	}

	if (!is_pow2_u64(*out_sectors)) {
		fprintf(stderr, "--sectors must be a power of two, not %" PRIu64 "\n",
			*out_sectors);
		return -1;
	}

	if (opts->dist == KV_DIST_ZIPF) {
		if (opts->zipf_theta <= 0.0 || opts->zipf_theta >= 1.0) {
			fprintf(stderr, "--zipf-theta must be in (0, 1), not %g\n",
				opts->zipf_theta);
			return -1;
		}
	} else if (opts->zipf_theta_set) {
		fprintf(stderr, "note: --zipf-theta given but --dist is 'uniform'; ignored\n");
	}

	if (!is_pow2_u64(opts->io_size_kib)) {
		fprintf(stderr, "--io-size-kib must be a power of two, not %u\n",
			opts->io_size_kib);
		return -1;
	}

	if (opts->num_seeds != 0 && opts->num_seeds != opts->num_trids) {
		fprintf(stderr,
			"%u --seed value(s) given for %u drive(s); pass one per -t, or omit\n",
			opts->num_seeds, opts->num_trids);
		return -1;
	}

	for (i = 0; i < opts->num_seeds; i++) {
		for (j = i + 1; j < opts->num_seeds; j++) {
			if (opts->seed[i] == opts->seed[j]) {
				fprintf(stderr,
					"--seed %" PRIu64 " given for both drive %u and %u; "
					"every drive must hold distinct data\n",
					opts->seed[i], i, j);
				return -1;
			}
		}
	}

	return 0;
}

static void
print_records(uint64_t seed, enum kv_dist dist, const struct zipf_table *zt, uint32_t count)
{
	uint32_t i;

	printf("kv_fill selftest: dist=%s seed=%" PRIu64,
	       dist == KV_DIST_ZIPF ? "zipf" : "uniform", seed);
	if (dist == KV_DIST_ZIPF) {
		printf(" theta=%.6f", zt->theta);
	}
	printf("\n%4s  %20s  %20s\n", "i", "key", "value");

	for (i = 0; i < count; i++) {
		uint64_t key_draw = splitmix64(seed, 2ULL * i);
		uint64_t value = splitmix64(seed, 2ULL * i + 1);
		uint64_t key = dist == KV_DIST_ZIPF ?
			       zipf_rank(zt, splitmix64_to_unit(key_draw)) :
			       key_draw % KV_FILL_KEY_MOD;

		printf("%4u  %20" PRIu64 "  %20" PRIu64 "\n", i, key, value);
	}
}

/* No hardware, no hugepages: pure host arithmetic, so this can run in any environment. */
static int
run_selftest(const struct kv_fill_opts *opts)
{
	struct zipf_table zt;
	uint64_t seed = opts->num_seeds > 0 ? opts->seed[0] : 1;

	if (opts->dist == KV_DIST_ZIPF) {
		if (opts->zipf_theta <= 0.0 || opts->zipf_theta >= 1.0) {
			fprintf(stderr, "--zipf-theta must be in (0, 1), not %g\n",
				opts->zipf_theta);
			return 1;
		}
		zipf_table_init(&zt, KV_FILL_KEY_MOD, opts->zipf_theta);
	}

	print_records(seed, opts->dist, &zt, 8);
	return 0;
}

/*
 * Fills `nrecs` records starting at record index `first_index` of drive `d`'s stream into `buf`,
 * and folds each one into d->group_sum/d->group_count/d->oor_count as it goes -- the drive's own
 * thread is the only reader or writer of those, so this needs no locking. Accumulation happens
 * here, at generation time, i.e. it counts records kv_fill ATTEMPTED to write. If the write this
 * buffer belongs to later fails, the run as a whole is marked "error" in the sidecar (see
 * write_sidecar()) rather than trying to unwind a partial group-table update.
 */
static void
generate_records(struct drive_ctx *d, uint64_t first_index, uint32_t nrecs, uint8_t *buf)
{
	uint32_t r;

	for (r = 0; r < nrecs; r++) {
		uint64_t idx = first_index + r;
		uint64_t key_draw = splitmix64(d->seed, 2 * idx);
		uint64_t value = splitmix64(d->seed, 2 * idx + 1);
		uint64_t key;

		if (d->dist == KV_DIST_ZIPF) {
			key = zipf_rank(d->zt, splitmix64_to_unit(key_draw));
		} else {
			key = key_draw % KV_FILL_KEY_MOD;
		}

		if (key < KV_FILL_KEY_MOD) {
			d->group_sum[key] += value;
			d->group_count[key]++;
		} else {
			d->oor_count++;
		}

		store_le64(buf + (size_t)r * KV_REC_BYTES, key);
		store_le64(buf + (size_t)r * KV_REC_BYTES + 8, value);
	}
}

/* One outstanding write command's buffer and bookkeeping. busy is cleared only by this exact
 * slot's own completion callback, so reuse never assumes a completion order the NVMe spec does
 * not guarantee. */
struct io_slot {
	uint8_t			*buf;
	uint32_t		sectors;
	uint64_t		lba;
	bool			busy;
	struct drive_ctx	*drive;
};

static void
write_complete_cb(void *arg, const struct spdk_nvme_cpl *cpl)
{
	struct io_slot *slot = arg;
	struct drive_ctx *d = slot->drive;

	if (spdk_nvme_cpl_is_error(cpl)) {
		if (!d->had_error) {
			fprintf(stderr, "[drive %u %s] write at LBA %" PRIu64 " failed: %s\n",
				d->index, d->trid.traddr, slot->lba,
				spdk_nvme_cpl_get_status_string(&cpl->status));
			d->first_error_lba = slot->lba;
		}
		d->had_error = true;
	} else {
		d->sectors_done += slot->sectors;
	}
	slot->busy = false;
}

/* Turns a transport address such as "0000:61:00.0" into a boring filename fragment. */
static void
sanitize_for_filename(char *out, size_t out_len, const char *in)
{
	size_t i;

	for (i = 0; in[i] != '\0' && i + 1 < out_len; i++) {
		out[i] = (isalnum((unsigned char)in[i]) || in[i] == '-' || in[i] == '.') ?
			 in[i] : '_';
	}
	out[i] = '\0';
}

/*
 * Writes one drive's reference sidecar as JSON (format "kv_fill.sidecar.v1"). group_sum/
 * group_count are per key in [0, KV_FILL_KEY_MOD), wrapped modulo 2^64 exactly like the FPGA's
 * accumulator and like apps/iuventus/sw/iuventus_groupby.py's reference() -- so a multi-drive
 * expected table is the elementwise, still-wrapped sum of several drives' group_sum arrays, the
 * same way the core itself sums every enabled queue into one table. Every integer is written as
 * a bare JSON number, never a string: Python's json module parses integer literals as arbitrary-
 * precision int, so the full uint64_t range round-trips exactly. seed/distribution/sector range
 * are included so a later run can prove it is looking at the right dataset.
 */
static void
write_sidecar(struct drive_ctx *d)
{
	char fname[SPDK_NVMF_TRADDR_MAX_LEN + 64];
	char sanitized[SPDK_NVMF_TRADDR_MAX_LEN + 1];
	FILE *fp;
	size_t i;
	const char *dist_str = d->dist == KV_DIST_ZIPF ? "zipf" : "uniform";

	sanitize_for_filename(sanitized, sizeof(sanitized), d->trid.traddr);
	snprintf(fname, sizeof(fname), "kv_fill_%s_seed%" PRIu64 ".json", sanitized, d->seed);
	snprintf(d->sidecar_path, sizeof(d->sidecar_path), "%s/%s", d->sidecar_dir, fname);

	fp = fopen(d->sidecar_path, "w");
	if (fp == NULL) {
		fprintf(stderr, "[drive %u %s] cannot write sidecar '%s': %s\n", d->index,
			d->trid.traddr, d->sidecar_path, strerror(errno));
		return;
	}

	fprintf(fp, "{\n");
	fprintf(fp, "  \"format\": \"kv_fill.sidecar.v1\",\n");
	fprintf(fp, "  \"trid\": \"%s\",\n", d->trid.traddr);
	fprintf(fp, "  \"drive_index\": %u,\n", d->index);
	fprintf(fp, "  \"seed\": %" PRIu64 ",\n", d->seed);
	fprintf(fp, "  \"distribution\": \"%s\",\n", dist_str);
	if (d->dist == KV_DIST_ZIPF) {
		fprintf(fp, "  \"zipf_theta\": %.6f,\n", d->zipf_theta);
	} else {
		fprintf(fp, "  \"zipf_theta\": null,\n");
	}
	fprintf(fp, "  \"key_mod\": %u,\n", KV_FILL_KEY_MOD);
	fprintf(fp, "  \"record_bytes\": %u,\n", KV_REC_BYTES);
	fprintf(fp, "  \"sector_bytes\": %u,\n", KV_SECT_BYTES);
	fprintf(fp, "  \"records_per_sector\": %u,\n", KV_RECS_PER_SECTOR);
	fprintf(fp, "  \"start_lba\": %" PRIu64 ",\n", d->start_lba);
	fprintf(fp, "  \"sectors\": %" PRIu64 ",\n", d->total_sectors);
	fprintf(fp, "  \"record_count\": %" PRIu64 ",\n", d->total_sectors * KV_RECS_PER_SECTOR);
	fprintf(fp, "  \"sectors_written\": %" PRIu64 ",\n", d->sectors_done);
	fprintf(fp, "  \"num_groups\": %u,\n", KV_FILL_KEY_MOD);
	fprintf(fp, "  \"oor_count\": %" PRIu64 ",\n", d->oor_count);
	fprintf(fp, "  \"error\": %s,\n", d->had_error ? "true" : "false");
	if (d->had_error) {
		fprintf(fp, "  \"first_error_lba\": %" PRIu64 ",\n", d->first_error_lba);
	} else {
		fprintf(fp, "  \"first_error_lba\": null,\n");
	}
	fprintf(fp, "  \"elapsed_seconds\": %.3f,\n", d->elapsed_seconds);
	fprintf(fp, "  \"throughput_gbps\": %.3f,\n", d->throughput_gbps);

	fprintf(fp, "  \"group_sum\": [");
	for (i = 0; i < KV_FILL_KEY_MOD; i++) {
		fprintf(fp, "%s%" PRIu64, i == 0 ? "" : ",", d->group_sum[i]);
	}
	fprintf(fp, "],\n");

	fprintf(fp, "  \"group_count\": [");
	for (i = 0; i < KV_FILL_KEY_MOD; i++) {
		fprintf(fp, "%s%" PRIu64, i == 0 ? "" : ",", d->group_count[i]);
	}
	fprintf(fp, "]\n");
	fprintf(fp, "}\n");

	fclose(fp);
}

/*
 * Body of one drive's fill thread: allocate its own I/O qpair and DMA buffers, stream writes
 * across `queue_depth` outstanding slots until `total_sectors` are issued and confirmed, then
 * write the sidecar. Nothing here touches another drive's state, so no locking is needed anywhere
 * in this function.
 */
static void *
fill_worker(void *arg)
{
	struct drive_ctx *d = arg;
	struct spdk_nvme_io_qpair_opts qpair_opts;
	struct io_slot *slots = NULL;

	pin_worker_to_own_cpu(d->index);
	uint8_t *buf_base = NULL;
	struct timespec t_start, t_end;
	uint32_t sector_size, max_xfer, io_size_sectors;
	uint64_t io_size_bytes, total_bytes, lba_cursor, sectors_remaining;
	uint32_t slot_idx, i;
	int last_pct;

	sector_size = spdk_nvme_ns_get_sector_size(d->ns);
	max_xfer = spdk_nvme_ns_get_max_io_xfer_size(d->ns);
	io_size_sectors = (uint32_t)spdk_min((uint64_t)d->io_size_kib * 1024 / sector_size,
					     (uint64_t)max_xfer / sector_size);
	io_size_sectors = spdk_max(io_size_sectors, 1u);
	io_size_bytes = (uint64_t)io_size_sectors * sector_size;

	spdk_nvme_ctrlr_get_default_io_qpair_opts(d->ctrlr, &qpair_opts, sizeof(qpair_opts));
	qpair_opts.io_queue_requests = spdk_max(qpair_opts.io_queue_requests, d->queue_depth + 4);
	qpair_opts.io_queue_size = spdk_max(qpair_opts.io_queue_size, d->queue_depth + 4);

	d->qpair = spdk_nvme_ctrlr_alloc_io_qpair(d->ctrlr, &qpair_opts, sizeof(qpair_opts));
	if (d->qpair == NULL) {
		fprintf(stderr, "[drive %u %s] spdk_nvme_ctrlr_alloc_io_qpair() failed\n",
			d->index, d->trid.traddr);
		d->had_error = true;
		goto out;
	}

	total_bytes = (uint64_t)d->queue_depth * io_size_bytes;
	slots = calloc(d->queue_depth, sizeof(*slots));
	buf_base = spdk_zmalloc(total_bytes, 0x1000, NULL, SPDK_ENV_NUMA_ID_ANY, SPDK_MALLOC_DMA);
	if (slots == NULL || buf_base == NULL) {
		fprintf(stderr, "[drive %u %s] failed to allocate %" PRIu64 " B of DMA buffer\n",
			d->index, d->trid.traddr, total_bytes);
		d->had_error = true;
		goto out;
	}

	for (i = 0; i < d->queue_depth; i++) {
		slots[i].buf = buf_base + (size_t)i * io_size_bytes;
		slots[i].drive = d;
	}

	printf("[drive %u %s] filling %" PRIu64 " sectors from LBA %" PRIu64 ", seed=%"
	       PRIu64 ", dist=%s, io=%" PRIu64 " B, qd=%u\n", d->index, d->trid.traddr,
	       d->total_sectors, d->start_lba, d->seed,
	       d->dist == KV_DIST_ZIPF ? "zipf" : "uniform", io_size_bytes, d->queue_depth);
	fflush(stdout);

	clock_gettime(CLOCK_MONOTONIC, &t_start);

	lba_cursor = d->start_lba;
	sectors_remaining = d->total_sectors;
	slot_idx = 0;
	last_pct = -1;

	while (sectors_remaining > 0 && !d->had_error) {
		struct io_slot *slot = &slots[slot_idx];
		uint64_t first_record;
		uint32_t chunk;
		int pct, rc;

		while (slot->busy && !d->had_error) {
			if (spdk_nvme_qpair_process_completions(d->qpair, 0) < 0) {
				fprintf(stderr, "[drive %u %s] qpair failed while draining\n",
					d->index, d->trid.traddr);
				d->had_error = true;
			}
		}
		if (d->had_error) {
			break;
		}

		chunk = (uint32_t)spdk_min((uint64_t)io_size_sectors, sectors_remaining);
		first_record = (lba_cursor - d->start_lba) * KV_RECS_PER_SECTOR;
		generate_records(d, first_record, chunk * KV_RECS_PER_SECTOR, slot->buf);

		rc = spdk_nvme_ns_cmd_write(d->ns, d->qpair, slot->buf, lba_cursor, chunk,
					    write_complete_cb, slot, 0);
		if (rc != 0) {
			fprintf(stderr, "[drive %u %s] write submit at LBA %" PRIu64
				" failed: %s\n", d->index, d->trid.traddr, lba_cursor,
				spdk_strerror(-rc));
			d->had_error = true;
			d->first_error_lba = lba_cursor;
			break;
		}

		slot->sectors = chunk;
		slot->lba = lba_cursor;
		slot->busy = true;

		lba_cursor += chunk;
		sectors_remaining -= chunk;
		slot_idx = (slot_idx + 1) % d->queue_depth;

		spdk_nvme_qpair_process_completions(d->qpair, 0);

		pct = (int)(100ULL * (d->total_sectors - sectors_remaining) / d->total_sectors);
		if (pct / 5 != last_pct / 5) {
			printf("[drive %u %s] %3d%%\n", d->index, d->trid.traddr, pct);
			fflush(stdout);
			last_pct = pct;
		}
	}

	/* Drain every command still in flight, even after an early error -- their buffers must
	 * outlive the controller's DMA into them, not just the submission loop above. */
	for (i = 0; i < d->queue_depth; i++) {
		while (slots[i].busy) {
			if (spdk_nvme_qpair_process_completions(d->qpair, 0) < 0) {
				break;
			}
		}
	}

	clock_gettime(CLOCK_MONOTONIC, &t_end);
	d->elapsed_seconds = (double)(t_end.tv_sec - t_start.tv_sec) +
			     (double)(t_end.tv_nsec - t_start.tv_nsec) / 1.0e9;
	if (d->elapsed_seconds > 0.0) {
		d->throughput_gbps =
			(double)d->sectors_done * sector_size / d->elapsed_seconds / 1.0e9;
	}

	printf("[drive %u %s] done: %" PRIu64 " / %" PRIu64 " sectors written, oor=%"
	       PRIu64 ", %.2f s, %.2f GB/s%s\n", d->index, d->trid.traddr, d->sectors_done,
	       d->total_sectors, d->oor_count, d->elapsed_seconds, d->throughput_gbps,
	       d->had_error ? " *** ERROR ***" : "");

out:
	spdk_free(buf_base);
	free(slots);
	if (d->qpair != NULL) {
		spdk_nvme_ctrlr_free_io_qpair(d->qpair);
		d->qpair = NULL;
	}

	write_sidecar(d);
	return NULL;
}

/* Index of the requested drive with this transport address, or -1. kv_fill only ever attaches to
 * a BDF that was named on the command line via -t: there is no "attach everything" mode, so a
 * drive never explicitly requested -- such as the host's own OS drive -- is never touched. */
static int
drive_by_traddr(const struct kv_fill_ctx *ctx, const char *traddr)
{
	uint32_t i;

	for (i = 0; i < ctx->num_drives; i++) {
		if (strcmp(ctx->drives[i].trid.traddr, traddr) == 0) {
			return (int)i;
		}
	}
	return -1;
}

static bool
probe_cb(void *cb_ctx, const struct spdk_nvme_transport_id *trid,
	 struct spdk_nvme_ctrlr_opts *opts)
{
	const struct kv_fill_ctx *ctx = cb_ctx;

	if (drive_by_traddr(ctx, trid->traddr) < 0) {
		return false;
	}

	printf("attaching %s ...\n", trid->traddr);
	/* Let the driver clamp this to whatever the controller actually supports; fill_worker()
	 * reads the negotiated size back via spdk_nvme_ctrlr_get_default_io_qpair_opts(). */
	opts->io_queue_size = UINT16_MAX;
	return true;
}

static void
attach_cb(void *cb_ctx, const struct spdk_nvme_transport_id *trid,
	  struct spdk_nvme_ctrlr *ctrlr, const struct spdk_nvme_ctrlr_opts *opts)
{
	struct kv_fill_ctx *ctx = cb_ctx;
	struct drive_ctx *d;
	struct spdk_nvme_ns *ns;
	int idx;
	int nsid;

	idx = drive_by_traddr(ctx, trid->traddr);
	if (idx < 0) {
		fprintf(stderr, "attached %s was never requested\n", trid->traddr);
		return;
	}
	d = &ctx->drives[idx];
	d->ctrlr = ctrlr;

	nsid = spdk_nvme_ctrlr_get_first_active_ns(ctrlr);
	ns = spdk_nvme_ctrlr_get_ns(ctrlr, nsid);
	if (ns == NULL || !spdk_nvme_ns_is_active(ns)) {
		fprintf(stderr, "%s has no active namespace\n", trid->traddr);
		return;
	}
	d->ns = ns;

	printf("attached %s: %" PRIu64 " sectors x %u B\n", trid->traddr,
	       spdk_nvme_ns_get_num_sectors(ns), spdk_nvme_ns_get_sector_size(ns));
}

static void
detach_all(struct kv_fill_ctx *ctx)
{
	struct spdk_nvme_detach_ctx *detach_ctx = NULL;
	uint32_t i;

	for (i = 0; i < ctx->num_drives; i++) {
		if (ctx->drives[i].ctrlr != NULL) {
			spdk_nvme_detach_async(ctx->drives[i].ctrlr, &detach_ctx);
		}
	}
	if (detach_ctx != NULL) {
		spdk_nvme_detach_poll(detach_ctx);
	}
}

int
main(int argc, char **argv)
{
	struct kv_fill_opts opts;
	struct kv_fill_ctx ctx;
	struct spdk_env_opts env_opts;
	struct zipf_table zt;
	pthread_t threads[KV_FILL_MAX_DRIVES];
	bool thread_started[KV_FILL_MAX_DRIVES];
	uint64_t sectors;
	uint32_t i;
	int rc;
	bool overall_error = false;

	opts_init(&opts);
	if (parse_args(argc, argv, &opts) != 0) {
		return 1;
	}

	if (opts.selftest) {
		return run_selftest(&opts);
	}

	if (validate_opts(&opts, &sectors) != 0) {
		return 1;
	}

	memset(&ctx, 0, sizeof(ctx));
	memset(thread_started, 0, sizeof(thread_started));
	ctx.num_drives = opts.num_trids;
	if (opts.dist == KV_DIST_ZIPF) {
		zipf_table_init(&zt, KV_FILL_KEY_MOD, opts.zipf_theta);
	}

	for (i = 0; i < ctx.num_drives; i++) {
		struct drive_ctx *d = &ctx.drives[i];

		d->index = i;
		d->trid = opts.trid[i];
		d->seed = opts.num_seeds > 0 ? opts.seed[i] : (uint64_t)(i + 1);
		d->dist = opts.dist;
		d->zipf_theta = opts.zipf_theta;
		d->zt = &zt;
		d->start_lba = opts.start_lba;
		d->total_sectors = sectors;
		d->io_size_kib = opts.io_size_kib;
		d->queue_depth = opts.queue_depth;
		d->sidecar_dir = opts.sidecar_dir;
		d->group_sum = calloc(KV_FILL_KEY_MOD, sizeof(*d->group_sum));
		d->group_count = calloc(KV_FILL_KEY_MOD, sizeof(*d->group_count));
		if (d->group_sum == NULL || d->group_count == NULL) {
			fprintf(stderr, "out of memory allocating the per-group tables\n");
			return 1;
		}
	}

	CPU_ZERO(&g_startup_cpus);
	if (sched_getaffinity(0, sizeof(g_startup_cpus), &g_startup_cpus) == 0) {
		g_startup_cpu_count = CPU_COUNT(&g_startup_cpus);
	}

	spdk_env_opts_init(&env_opts);
	env_opts.name = "kv_fill";
	if (spdk_env_init(&env_opts) < 0) {
		fprintf(stderr, "unable to initialize the SPDK env\n");
		return 1;
	}

	printf("probing %u drive(s)...\n", ctx.num_drives);
	if (spdk_nvme_probe(NULL, &ctx, probe_cb, attach_cb, NULL) != 0) {
		fprintf(stderr, "spdk_nvme_probe() failed\n");
		spdk_env_fini();
		return 1;
	}

	for (i = 0; i < ctx.num_drives; i++) {
		struct drive_ctx *d = &ctx.drives[i];

		if (d->ctrlr == NULL || d->ns == NULL) {
			fprintf(stderr, "%s did not attach -- is it bound to uio_pci_generic?\n",
				d->trid.traddr);
			overall_error = true;
			continue;
		}
		if (spdk_nvme_ns_get_sector_size(d->ns) != KV_SECT_BYTES) {
			fprintf(stderr, "%s: sector size %u B, kv_fill assumes %u B\n",
				d->trid.traddr, spdk_nvme_ns_get_sector_size(d->ns),
				KV_SECT_BYTES);
			overall_error = true;
			continue;
		}
		if (d->start_lba + d->total_sectors > spdk_nvme_ns_get_num_sectors(d->ns)) {
			fprintf(stderr, "%s: [%" PRIu64 ", %" PRIu64 ") does not fit the "
					"namespace's %" PRIu64 " sectors\n", d->trid.traddr,
				d->start_lba, d->start_lba + d->total_sectors,
				spdk_nvme_ns_get_num_sectors(d->ns));
			overall_error = true;
		}
	}

	if (overall_error) {
		detach_all(&ctx);
		spdk_env_fini();
		return 1;
	}

	printf("starting %u parallel fill(s), %" PRIu64 " sectors (%" PRIu64 " records) each\n",
	       ctx.num_drives, sectors, sectors * KV_RECS_PER_SECTOR);

	for (i = 0; i < ctx.num_drives; i++) {
		rc = pthread_create(&threads[i], NULL, fill_worker, &ctx.drives[i]);
		if (rc != 0) {
			fprintf(stderr, "pthread_create() failed for drive %u: %s\n", i,
				strerror(rc));
			ctx.drives[i].had_error = true;
			overall_error = true;
		} else {
			thread_started[i] = true;
		}
	}

	for (i = 0; i < ctx.num_drives; i++) {
		if (thread_started[i]) {
			pthread_join(threads[i], NULL);
		}
	}

	printf("\n=== summary ===\n");
	for (i = 0; i < ctx.num_drives; i++) {
		struct drive_ctx *d = &ctx.drives[i];

		printf("drive %u %-14s seed=%-10" PRIu64 " records=%-14" PRIu64 " %6.2f GB/s  "
		       "%s  sidecar=%s\n", d->index, d->trid.traddr, d->seed,
		       d->sectors_done * KV_RECS_PER_SECTOR, d->throughput_gbps,
		       d->had_error ? "ERROR" : "OK", d->sidecar_path);
		overall_error |= d->had_error;
	}

	detach_all(&ctx);
	spdk_env_fini();

	for (i = 0; i < ctx.num_drives; i++) {
		free(ctx.drives[i].group_sum);
		free(ctx.drives[i].group_count);
	}

	return overall_error ? 1 : 0;
}
